"""Export the frozen numerical baseline; no tuning/design on the MCU."""
from pathlib import Path
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parents[2]
MODEL = ROOT / "models/minisegway"

def generate():
    paths = [MODEL / p for p in (
        "stage3/results/config/baseline.json", "stage2/results/full_state_identification_results.json",
        "stage3/results/config/stage3a_velocity_feedforward_lean_tail_config.json",
        "stage6/config/stage6_4_2d_follow_config.json", "longitudinal_estimator_config.json",
        "encoder_profile.json", "reduced_twip.json", "plant_parameters.json")]
    manifest, offline, runtime, follow, estimator, encoder, reduced, plant = [
        json.loads(p.read_text()) for p in paths]
    yaw, safety = follow["yaw"], follow["safety"]
    values = {
        "CB_NOMINAL_PITCH": reduced["parameters"]["theta_eq_rad"],
        "CB_WHEEL_RADIUS": reduced["parameters"]["wheel_radius_m"],
        "CB_WHEEL_LIMIT": plant["known"]["wheel_torque_hard_peak_nm"],
        "CB_LAMBDA_FF": runtime["lambda_ff"],
        "CB_YAW_KP": manifest["yaw"]["K_psi_nm_per_rad"],
        "CB_YAW_KR": manifest["yaw"]["K_r_nm_per_rad_s"],
        "CB_PITCH_TAU": estimator["imu_complementary_filter"]["time_constant_s"],
        "CB_PLL_BANDWIDTH": estimator["encoder_velocity"]["pll"]["selected_bandwidth_rad_s"],
        "CB_PLL_SNAP": int(estimator["encoder_velocity"]["pll"]["snap_to_zero"]),
        "CB_COUNTS_PER_REV": encoder["output_decoded_counts_per_rev"],
        "CB_LEFT_SIGN": encoder["left_count_sign"], "CB_RIGHT_SIGN": encoder["right_count_sign"],
        "CB_ACCEL_TAU": 0.05, "CB_ACCEL_SCALE": 0.25,
        "CB_SAFE_DECEL": safety["safe_max_deceleration_m_s2"],
        "CB_SAFE_JERK": safety["safe_max_jerk_m_s3"],
        "CB_SAFE_HANDOFF": safety["hidden_reference_handoff_time_s"],
        "CB_HEARTBEAT_TIMEOUT": safety["heartbeat_timeout_s"],
        "CB_STARVATION_MARGIN": safety["reference_starvation_margin_s"],
        "CB_YAW_TIMEOUT": yaw["freshness_timeout_s"], "CB_YAW_DECAY": yaw["decay_rate_rad_s2"],
    }
    assert manifest["timing"] == {"physics_dt_s": 0.001, "controller_dt_s": 0.002}
    assert estimator["sample_period_s"] == 0.002
    assert manifest["disturbance_rejection"]["actuator_augmentation_production_enabled"] is False
    gain = [float(v) for v in offline["identified_lqr"]["K_id"][0]]
    lines = ["/* Generated by tools/embedded/export_frozen_config.py; frozen simulation",
             " * calibration only. Physical motor/sensor calibration remains unverified. */",
             "#ifndef COMPANIONBOT_FROZEN_CONFIG_H", "#define COMPANIONBOT_FROZEN_CONFIG_H"]
    lines += [f"#define {k} {repr(v)}" for k, v in values.items()]
    lines += ["#define CB_LQR_GAIN {" + ", ".join(map(repr, gain)) + "}", "#endif", ""]
    sources = {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in paths}
    # Acceleration compensation is defined in the existing estimator implementation.
    code = ROOT / "ros2_ws/src/companionbot_control/companionbot_control/estimation/longitudinal_estimation.py"
    sources[str(code.relative_to(ROOT))] = hashlib.sha256(code.read_bytes()).hexdigest()
    return "\n".join(lines), json.dumps({"sources_sha256": sources, "K_id": gain,
        "values": values, "Q_actuator": False, "hardware_calibration_validated": False}, indent=2) + "\n"

def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--check", action="store_true")
    args = cli.parse_args()
    header, manifest = generate()
    target = ROOT / "firmware/generated"
    for name, text in (("frozen_config.h", header), ("frozen_config.json", manifest)):
        path = target / name
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit(f"Frozen configuration differs: {path}")
        else:
            target.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print("Frozen configuration " + ("verified" if args.check else "exported"))

if __name__ == "__main__":
    main()
